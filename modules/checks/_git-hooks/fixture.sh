set -euo pipefail
export HOME="$TMPDIR" PREK_HOME="$TMPDIR/prek-cache"
export registrationLog="$TMPDIR/registrations"
git config --global user.email fixture@example.invalid
git config --global user.name Fixture
git config --global init.defaultBranch main
git config --global protocol.file.allow always
cd "$TMPDIR"
git init -q child
git -C child commit -q --allow-empty -m init
git init -q parent
git -C parent commit -q --allow-empty -m init
git -C parent submodule add -q "$TMPDIR/child" sub
git -C parent commit -q -m submodule
git -C parent worktree add -q --detach "$TMPDIR/parent-wt"
git -C parent/sub worktree add -q --detach "$TMPDIR/sub-wt"

# Use real prek-generated hooks, including the current marker and quoting.
for checkout in parent parent-wt parent/sub sub-wt; do
  (
    cd "$checkout"
    "$isolate"
    hooks="$(git rev-parse --path-format=absolute --git-path hooks)"
    test "$hooks" = "$(git rev-parse --absolute-git-dir)/hooks"
    printf 'repos: []\n' > 'config with spaces.yaml'
    prek install --config "$PWD/config with spaces.yaml"
    cp "$hooks/pre-commit" "$TMPDIR/$(basename "$checkout").original"
    # Replace an old managed root, leaving unrelated symlinks untouched.
    ln -s "$prekStore" "$hooks/.agentic-prek-gc-root-obsolete"
    ln -s "$prekStore" "$hooks/keep-root"
    "$root"
    test ! -L "$hooks/.agentic-prek-gc-root-obsolete"
    test -L "$hooks/keep-root"
    gc_root="$hooks/.agentic-prek-gc-root-$(basename "$prekStore")"
    test -L "$gc_root"
    test "$(readlink "$gc_root")" = "$prekStore"
    grep -qF "PREK=\"$(readlink "$gc_root")/bin/prek\"" "$hooks/pre-commit"
    "$root"
    test -L "$gc_root"
  )
done
test "$(wc -l < "$registrationLog" | tr -d ' ')" = 8
# Daemon/sandbox failures must not prevent shell entry or retire old roots.
(
  cd parent
  hooks="$(git rev-parse --path-format=absolute --git-path hooks)"
  ln -s "$prekStore" "$hooks/.agentic-prek-gc-root-obsolete"
  failRootRegistration=1 "$root" 2> "$TMPDIR/root-warning"
  test -L "$hooks/.agentic-prek-gc-root-obsolete"
  test -L "$hooks/.agentic-prek-gc-root-$(basename "$prekStore")"
  grep -qF "warning: cannot register prek GC roots in $hooks" "$TMPDIR/root-warning"
  test "$(wc -l < "$TMPDIR/root-warning" | tr -d ' ')" = 1
  "$root"
  test ! -L "$hooks/.agentic-prek-gc-root-obsolete"
)
"$doctor" parent
# Invoking from a linked worktree discovers the whole repository as well.
"$doctor" parent-wt
"$doctor" parent/sub

main_hooks="$(git -C parent rev-parse --path-format=absolute --git-path hooks)"
wt_hooks="$(git -C parent-wt rev-parse --path-format=absolute --git-path hooks)"
sub_hooks="$(git -C parent/sub rev-parse --path-format=absolute --git-path hooks)"
sub_wt_hooks="$(git -C sub-wt rev-parse --path-format=absolute --git-path hooks)"
# Poison one embedded executable without touching the config or any other hook.
python3 - "$main_hooks/pre-commit" <<'PY'
from pathlib import Path
import re
import sys
hook = Path(sys.argv[1])
hook.write_text(re.sub(r'^PREK="[^"]+"', 'PREK="/nix/store/00000000000000000000000000000000-missing-prek/bin/prek"', hook.read_text(), count=1, flags=re.M))
PY
# Missing absolute config in a submodule gitdir, plus a relative config in its
# linked worktree. The latter proves checkout association, not just path tests.
rm 'parent/sub/config with spaces.yaml'
python3 - "$sub_wt_hooks/pre-commit" <<'PY'
from pathlib import Path
import re
import sys
hook = Path(sys.argv[1])
hook.write_text(re.sub(r'--config="[^"]+"', '--config="missing-relative.yaml"', hook.read_text()))
PY
# Hand-written hooks (even broken ones), samples and legacy files are sacrosanct.
printf '#!/bin/sh\nexec /nix/store/missing/bin/prek\n' > "$main_hooks/pre-push"
printf 'hand written\n' > "$sub_hooks/pre-commit.legacy"
printf '# File generated by pre-commit\nexec /missing\n' > "$wt_hooks/post-commit"
cp "$main_hooks/pre-push" handwritten
cp "$sub_hooks/pre-commit.legacy" legacy
cp "$wt_hooks/post-commit" other-generator

if "$doctor" parent > report; then echo 'doctor missed dangling hooks' >&2; exit 1; fi
grep -qF "$main_hooks/pre-commit: missing prek:" report
grep -qF "$sub_hooks/pre-commit: missing config:" report
grep -qF "$sub_wt_hooks/pre-commit: missing config:" report
test "$(wc -l < report | tr -d ' ')" = 3
# A report is read-only.
test -f "$main_hooks/pre-commit"
test -f "$sub_hooks/pre-commit"
test -f "$sub_wt_hooks/pre-commit"
if "$doctor" --fix parent > fixed; then echo 'fix should report found hooks' >&2; exit 1; fi
test ! -e "$main_hooks/pre-commit"
test ! -e "$sub_hooks/pre-commit"
test ! -e "$sub_wt_hooks/pre-commit"
cmp "$wt_hooks/pre-commit" "$TMPDIR/parent-wt.original"
cmp "$main_hooks/pre-push" handwritten
cmp "$sub_hooks/pre-commit.legacy" legacy
cmp "$wt_hooks/post-commit" other-generator
test -f 'parent/config with spaces.yaml'
test -f 'sub-wt/config with spaces.yaml'
test -L "$main_hooks/.agentic-prek-gc-root-$(basename "$prekStore")"
"$doctor" parent
"$doctor" --fix parent

# Before isolation, the common hook dir can serve multiple checkouts. A
# relative config missing in only one checkout is reported but not removable.
git init -q shared
git -C shared commit -q --allow-empty -m init
git -C shared worktree add -q --detach "$TMPDIR/shared-wt"
(
  cd shared
  printf 'repos: []\n' > .pre-commit-config.yaml
  prek install
)
shared_hook="$TMPDIR/shared/.git/hooks/pre-commit"
cp "$shared_hook" shared-original
if "$doctor" --fix shared > shared-report; then echo 'doctor missed shared config' >&2; exit 1; fi
grep -qF "$TMPDIR/shared-wt/.pre-commit-config.yaml" shared-report
grep -qF 'kept shared hook' shared-report
grep -qF 'agentic-worktree-hooks' shared-report
cmp "$shared_hook" shared-original
# Once the config is missing in every context, --fix may remove it.
rm shared/.pre-commit-config.yaml
if "$doctor" --fix shared > shared-fixed; then echo 'doctor missed all-context config' >&2; exit 1; fi
test ! -e "$shared_hook"
"$doctor" shared

# Removing a linked worktree's gitdir also removes its indirect root.
git -C parent worktree remove --force "$TMPDIR/parent-wt"
test ! -e "$wt_hooks"
test -d "$main_hooks"
"$doctor" parent
