"""Inspect prek hooks as data, never source or execute their shell contents."""

import argparse
import os
from pathlib import Path
import re
import shlex
import subprocess
import sys

MARKER = "# File generated by prek: https://github.com/j178/prek"
ROOT_PREFIX = ".agentic-prek-gc-root-"


def git(*args):
    return subprocess.check_output(
        ["git", *map(str, args)], text=True, stderr=subprocess.DEVNULL
    ).rstrip("\n")


def embedded(hook):
    try:
        contents = hook.read_text()
    except (OSError, UnicodeError):
        return None
    if MARKER not in contents.splitlines():
        return None
    # Read only literal assignments/arguments emitted by prek. In particular,
    # do not evaluate $(), variables, or any other shell program in a hook.
    match = re.search(r"^PREK=(.+)$", contents, re.MULTILINE)
    if not match:
        return None
    try:
        prek = shlex.split(match[1])[0]
        command = next(line for line in contents.splitlines() if line.startswith("exec "))
        args = shlex.split(command)
        config = next(
            (arg.split("=", 1)[1] for arg in args if arg.startswith("--config=")),
            None,
        )
        if config is None and "--config" in args:
            config = args[args.index("--config") + 1]
    except (ValueError, IndexError, StopIteration):
        return None
    return prek, config


def hook_files(directory):
    if directory.is_dir():
        # Never descend into hook directories or follow arbitrary directory links.
        yield from sorted(path for path in directory.iterdir() if path.is_file())


def gitdirs(common):
    """Include deinitialized submodules and stale worktree registrations too."""
    yield common
    modules = common / "modules"
    if modules.is_dir():
        for directory, children, files in os.walk(modules, followlinks=False):
            children[:] = [
                name for name in children if name not in {"objects", "logs", "refs", "hooks"}
            ]
            path = Path(directory)
            if "config" in files and "HEAD" in files:
                yield from gitdirs(path)
                children[:] = []
    worktrees = common / "worktrees"
    if worktrees.is_dir():
        for path in sorted(worktrees.iterdir()):
            if path.is_dir() and (path / "commondir").is_file():
                yield path
                # A submodule may be initialized only in a linked worktree.
                if (path / "modules").is_dir():
                    yield from (p for p in gitdirs(path) if p != path)


def checkouts(directory):
    if (directory / "gitdir").is_file():
        return [Path((directory / "gitdir").read_text().rstrip("\n")).parent]
    try:
        # The first record is this common gitdir's main checkout, even when
        # linked checkouts have disappeared (and are marked prunable).
        records = git("--git-dir", directory, "worktree", "list", "--porcelain", "-z").split("\0")
        return [Path(next(line[9:] for line in records if line.startswith("worktree ")))]
    except (subprocess.CalledProcessError, StopIteration):
        return []


def doctor(repository, fix):
    common = Path(git("-C", repository, "rev-parse", "--path-format=absolute", "--git-common-dir"))
    directories = {}
    for directory in gitdirs(common):
        contexts = checkouts(directory)
        directories.setdefault(directory / "hooks", set()).update(contexts)
        for checkout in contexts:
            try:
                # A stale checkout path may have been reused for an unrelated
                # repository. Never scan that new repository's effective hooks.
                actual = Path(git("-C", checkout, "rev-parse", "--absolute-git-dir"))
                if actual.resolve() == directory.resolve():
                    effective = Path(git("-C", checkout, "rev-parse", "--path-format=absolute", "--git-path", "hooks"))
                    directories.setdefault(effective, set()).add(checkout)
            except subprocess.CalledProcessError:
                pass
    found = 0
    for directory, contexts in sorted(directories.items()):
        for hook in hook_files(directory):
            data = embedded(hook)
            if data is None:
                continue
            prek, config = data
            reasons = []
            dangling_for_all = Path(prek).is_absolute() and not Path(prek).exists()
            if dangling_for_all:
                reasons.append(f"missing prek: {prek}")
            if config is not None and Path(config).is_absolute():
                if not Path(config).exists():
                    reasons.append(f"missing config: {config}")
                    dangling_for_all = True
            else:
                # With no --config argument prek discovers either default
                # format in the checkout; an explicit relative path is literal.
                candidates = [config] if config is not None else [".pre-commit-config.yaml", "prek.toml"]
                missing = [
                    checkout for checkout in sorted(contexts)
                    if not any((checkout / name).exists() for name in candidates)
                ]
                reasons.extend(
                    "missing config: " + " or ".join(str(checkout / name) for name in candidates)
                    for checkout in missing
                )
                dangling_for_all |= bool(contexts) and len(missing) == len(contexts)
            if reasons:
                found += 1
                print(f"{hook}: {'; '.join(reasons)}")
                if dangling_for_all and fix:
                    # Only unlink the generated hook itself, not its config,
                    # executable, GC root, legacy hook, or any parent directory.
                    hook.unlink()
                    print(f"removed {hook}")
                elif not dangling_for_all:
                    print(f"kept shared hook {hook}: still valid for another checkout; "
                          "run agentic-worktree-hooks or enter the shell in the checkout(s) "
                          "with missing config to isolate their hooks")
    # A fixing invocation still reports that dangling hooks were found.
    return 1 if found else 0


def register_roots():
    try:
        directory = Path(git("rev-parse", "--path-format=absolute", "--git-path", "hooks"))
    except (OSError, subprocess.CalledProcessError):
        print(f"agentic hooks: warning: cannot find hook directory in {Path.cwd()}; "
              "skipping prek GC root registration", file=sys.stderr)
        return 0
    stores = set()
    for hook in hook_files(directory):
        data = embedded(hook)
        if data is not None:
            match = re.fullmatch(r"(/nix/store/[^/]+)/bin/prek", data[0])
            if match:
                stores.add(Path(match[1]))
    roots = set()
    for store in sorted(stores):
        root = directory / (ROOT_PREFIX + store.name)
        # Register new roots before retiring old ones. The indirect root is
        # registered with the daemon; its target is the store output, not bin/prek.
        try:
            result = subprocess.run(
                ["nix-store", "--add-root", str(root), "--indirect", "--realise", str(store)],
                capture_output=True,
            )
            if result.returncode:
                raise OSError(f"nix-store exited {result.returncode}")
        except OSError:
            print(f"agentic hooks: warning: cannot register prek GC roots in {directory}; "
                  "leaving existing roots alone (Nix daemon/store may be unavailable)",
                  file=sys.stderr)
            return 0
        roots.add(root)
    if directory.is_dir():
        for previous in directory.glob(ROOT_PREFIX + "*"):
            if previous not in roots and previous.is_symlink():
                previous.unlink()
    return 0


def main():
    mode = sys.argv.pop(1)
    parser = argparse.ArgumentParser(description=__doc__)
    if mode == "doctor":
        parser.add_argument("--fix", action="store_true", help="remove only dangling prek-generated hooks")
        parser.add_argument("repository", nargs="?", default=".")
        args = parser.parse_args()
        return doctor(args.repository, args.fix)
    parser.parse_args()
    try:
        return register_roots()
    except (OSError, subprocess.CalledProcessError) as error:
        print(f"agentic hooks: warning: cannot maintain hook roots for {Path.cwd()}: {error}; "
              "continuing without GC protection", file=sys.stderr)
        return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (OSError, subprocess.CalledProcessError) as error:
        print(f"agentic hooks: {error}", file=sys.stderr)
        sys.exit(2)
